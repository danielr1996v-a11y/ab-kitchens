type KitchenPageContent = {
  /** הכותרת על גבי תמונת ההירו */
  heroTitle: string;
  heroImage: string;
  heroAlt: string;
  /**
   * גוף המאמר, מקובץ לפי כותרת.
   * כל בלוק מרונדר כזוג עמודות - כותרת מימין, תוכן משמאל - כדי
   * שהמאמר יישב על אותו גריד כמו שאר הסקשנים ולא יצוף באמצע.
   */
  article: Array<{
    /** אופציונלי - בלוק התמונה מוצג בלי כותרת */
    heading?: string;
    /** מוצגות אחרונות בבלוק - משמשות כמשפט סוגר */
    paragraphs?: string[];
    items?: string[];
    /** שלוש קוביות קצרות. מוצגות ראשונות בבלוק */
    cards?: string[];
    /**
     * תמונה עם נקודות חמות, במקום רשימת הבולטים בדסקטופ.
     *
     * ⚠️ x ו-y הם אחוזים מהתמונה שמצוינת כאן, ותקפים לה בלבד.
     * החלפת התמונה מחייבת כיול מחדש של כל הנקודות.
     * pos קובע לאיזה כיוון התווית נפתחת, כדי שלא תיחתך בקצה.
     */
    hotspots?: {
      image: string;
      alt: string;
      points: Array<{
        x: number;
        y: number;
        label: string;
        pos: "top" | "bottom";
      }>;
    };
  }>;
  galleryTitle: string;
  /** ⚠️ פלייסהולדרים. הצילומים האמיתיים יושבים בדרייב,
      בתיקייה "מטבחים שלנו" לפי סגנון. */
  gallery: Array<{ image: string; alt: string }>;
  /** שאלות ותשובות. משמשות גם ל-JSON-LD מסוג FAQPage */
  faqTitle: string;
  faq: Array<{ q: string; a: string }>;
};

