export type Testimonial = {
  id: string;
  /** הטקסט כפי שנכתב. כל פסקה איבר במערך */
  quote: string[];
  /** שם פרטי + אות, לפי ההכרעה של דניאל. ריק = לא ידוע */
  author?: string;
  /** עיר או שכונה, כשהיא מופיעה בצילום */
  place?: string;
  /** מאיפה ההמלצה הגיעה - מוצג כתווית */
  source: "וואטסאפ" | "מידרג" | "מכתב";
  /** הצילום המקורי. נפתח בלחיצה */
  image: string;
  imageAlt: string;
  /** מידות אמיתיות של הקובץ. בלעדיהן יש קפיצת פריסה בטעינה */
  w: number;
  h: number;
  /** תאריך, רק כשהוא מופיע בצילום */
  date?: string;
  /** דירוגי מידרג. מוצגים **כולל** הנמוך - כך הוכרע */
  scores?: { label: string; value: number }[];
};

