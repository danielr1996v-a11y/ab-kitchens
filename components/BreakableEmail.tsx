/**
 * כתובת מייל שמותר לה להישבר אחרי ה-@.
 *
 * ⚠️ 18.10: דניאל - "המייל גולש החוצה בטלפון, לא רואים אותו".
 * bk0552775488@gmail.com היא מילה אחת של ~200px, ובפוטר הדו-עמודתי
 * של הנייד העמודה היא ~160px: הדפדפן לא שובר אותה, והיא נחתכה
 * מעבר לקצה המסך. ‎<wbr> אחרי ה-@ נותן נקודת שבירה אחת ונקייה -
 * "bk0552775488@" ואז "gmail.com" - במקום שבירה באמצע אותיות.
 * ברוחב מלא ה-wbr לא עושה כלום והמייל נשאר בשורה אחת.
 */
export default function BreakableEmail({ email }: { email: string }) {
  const at = email.indexOf("@");
  if (at < 0) return <>{email}</>;
  return (
    <>
      {email.slice(0, at + 1)}
      <wbr />
      {email.slice(at + 1)}
    </>
  );
}
